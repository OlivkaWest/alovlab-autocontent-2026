def page(section, num, inner):
    return (f'<section class="page"><div class="ph">{BRAND}<span>{section}</span></div>'
            f'<div class="main">{inner}</div>'
            f'<div class="pf"><span>AlovLab · карта состояний</span><span class="pnum">стр. <b>{num:02d}</b></span></div></section>')
def head(kick, h2, lead=None):
    l = f'<p class="lead">{lead}</p>' if lead else ''
    return f'<span class="kick">{kick}</span><h2>{h2}</h2>{l}'
def rec(n,t,b): return f'<div class="rec"><div class="n">{n}</div><div class="t"><b>{t}</b><p>{b}</p></div></div>'
def do(steps): return '<div class="do">'+''.join(f'<div class="s"><div class="k">{i}</div><p>{t}</p></div>' for i,t in enumerate(steps,1))+'</div>'
def side(h,p): return f'<div class="side"><div class="h">{h}</div><p>{p}</p></div>'
def ex(h,paras): return f'<div class="ex"><div class="h">{h}</div>'+''.join(f'<p>{x}</p>' for x in paras)+'</div>'

def steppage(section, num, kick, title, zachem, dosteps, tag, code, swaps, good, bad, badwhy, push, take):
    swap_html = '<div class="swap">'+''.join(f'<div class="r"><b>{v}</b> → {ex_}</div>' for v,ex_ in swaps)+'</div>'
    prompt = (f'<div class="prompt"><div class="plbl"><span class="tag">{tag}</span><span class="copy">скопировать</span></div><code>{code}</code></div>')
    gp = (f'<div class="gp"><div class="c g"><b>Хороший ответ</b>{good}</div>'
          f'<div class="c b"><b>Плохой ответ</b>{bad}<br><i style="color:#c56b43">Почему мимо: {badwhy}</i></div></div>')
    pushb = f'<div class="push"><b>Если вышло слабо — скажи Claude</b><code>{push}</code></div>'
    takeb = f'<div class="take"><b>Забери:</b> {take[0]} <span class="ar">→</span> понадобится в шаге {take[1]}.</div>'
    return page(section, num,
        head(kick, title) + f'<div class="zap"><b>Зачем</b>{zachem}</div>'
        + '<span class="lbl">Что сделать</span>' + do(dosteps)
        + prompt + '<span class="lbl">Что заменить своим</span>' + swap_html + gp + pushb + takeb)

